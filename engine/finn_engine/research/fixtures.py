def r2(x: float) -> float:
    return round(x + 0.0, 2)


# ------------------------------------------------------------------ number formatting

def indian(v: float) -> str:
    s = f"{abs(v):.2f}"
    whole, dec = s.split(".")
    if len(whole) > 3:
        head, tail = whole[:-3], whole[-3:]
        parts = []
        while len(head) > 2:
            parts.insert(0, head[-2:])
            head = head[:-2]
        if head:
            parts.insert(0, head)
        whole = ",".join(parts + [tail])
    return f"{whole}.{dec}"


def fmt(v: float | None, unit: str) -> str:
    if v is None:
        return ""
    scale = {"crore": 1, "lakhs": 100, "million": 10}[unit]
    x = round(v * scale, 2)
    if abs(x) < 0.005:
        return "-"
    s = indian(x) if unit == "lakhs" else f"{abs(x):,.2f}"
    return f"({s})" if x < 0 else s


