def _cf(c: Co, spec: dict[str, tuple[float, float]]) -> dict[str, dict[str, float]]:
    """Cash flow lines per period from (OCF ÷ EBITDA, capex as % of revenue)."""
    out: dict[str, dict[str, float]] = {}
    for per, (conv, capex_pct) in spec.items():
        a = agg(c.pl, P.quarters(per))
        ebitda = a["pbt"] + a["finance_cost"] + a["dna"] - a["other_income"]
        cfo = r2(ebitda * conv)
        capex = r2(a["revenue"] * capex_pct / 100)
        out[per] = {"pbt": a["pbt"], "dna": a["dna"], "finance_cost": a["finance_cost"], "other_income": -a["other_income"],
                    "op_before_wc": r2(a["pbt"] + a["dna"] + a["finance_cost"] - a["other_income"]),
                    "wc": r2(cfo + a["tax"] - (a["pbt"] + a["dna"] + a["finance_cost"] - a["other_income"])), "tax_paid": -a["tax"], "cfo": cfo,
                    "capex": -capex, "capex_proceeds": r2(capex * 0.02), "investments_net": r2(-cfo * 0.3), "interest_received": a["other_income"],
                    "borrowings_net": r2(-cfo * 0.05), "interest_paid": -a["finance_cost"], "dividend": r2(-cfo * 0.4)}
        o = out[per]
        o["cfi"] = r2(o["capex"] + o["capex_proceeds"] + o["investments_net"] + o["interest_received"])
        o["cff"] = r2(o["borrowings_net"] + o["interest_paid"] + o["dividend"])
        o["net"] = r2(o["cfo"] + o["cfi"] + o["cff"])
    return out


