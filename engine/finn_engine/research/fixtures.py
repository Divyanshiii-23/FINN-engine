def corporate_pl(rev: list[float], ebitda_m: list[float], split: dict[str, float], dna_pct: float, fc_pct: float, oi_pct: float) -> dict[str, dict[str, float]]:
    """P&L per quarter from revenue, EBITDA margin and a fixed split of operating costs.

    `split` gives each cost line's share of revenue except `other_exp`, which
    absorbs the remainder so EBITDA lands exactly on the margin.
    """
    out: dict[str, dict[str, float]] = {}
    for q, r, m in zip(QS, rev, ebitda_m):
        d: dict[str, float] = {"revenue": r2(r)}
        for k, pct in split.items():
            d[k] = r2(r * pct / 100)
        ebitda = r2(r * m / 100)
        d["other_exp"] = r2(r - ebitda - sum(d[k] for k in split))
        d["dna"] = r2(r * dna_pct / 100)
        d["finance_cost"] = r2(r * fc_pct / 100)
        d["other_income"] = r2(r * oi_pct / 100)
        _close_pl(d)
        out[q] = d
    return out


def _close_pl(d: dict[str, float]) -> None:
    exp_keys = [k for k in ("materials", "purchases", "inventory_change", "power_fuel", "freight", "employee", "finance_cost", "impairment", "dna", "other_exp") if k in d]
    d.setdefault("exceptional", 0.0)
    d["total_income"] = r2(d["revenue"] + d["other_income"])
    d["total_exp"] = r2(sum(d[k] for k in exp_keys))
    d["pbt"] = r2(d["total_income"] - d["total_exp"])
    d["tax_current"] = r2(d["pbt"] * 0.2265)
    d["tax_deferred"] = r2(d["pbt"] * 0.0252)
    d["tax"] = r2(d["tax_current"] + d["tax_deferred"])
    d["pat"] = r2(d["pbt"] - d["tax"])
    d["oci"] = r2(-d["revenue"] * 0.0011)
    d["tci"] = r2(d["pat"] + d["oci"])


def agg(pl: dict[str, dict[str, float]], qs: list[str]) -> dict[str, float]:
    keys = pl[qs[0]].keys()
    return {k: r2(sum(pl[q][k] for q in qs)) for k in keys}


def balance(items: dict[str, float], fin: bool) -> dict[str, float]:
    """Fills `other_equity` so total assets equal total equity and liabilities."""
    d = dict(items)
    if fin:
        assets = ["cash", "bank_balances", "loans", "investments", "other_fin_assets", "ppe", "dta", "other_nonfin"]
        liab = ["debt_securities", "borrowings", "subordinated", "other_fin_liab", "provisions", "other_nonfin_liab"]
    else:
        assets = ["ppe", "cwip", "intangibles", "nc_investments", "nc_other_fin", "dta", "nc_other", "inventories", "investments", "receivables", "cash", "bank_balances", "c_other_fin", "c_other"]
        liab = ["nc_borrowings", "nc_lease", "nc_provisions", "dtl", "c_borrowings", "c_lease", "payables_msme", "payables_other", "c_other_fin_liab", "c_other_liab", "c_provisions", "tax_liab"]
    ta = r2(sum(d.get(k, 0) for k in assets))
    d["total_assets"] = ta
    d["other_equity"] = r2(ta - sum(d.get(k, 0) for k in liab) - d["share_capital"])
    d["total_equity"] = r2(d["share_capital"] + d["other_equity"])
    return d


