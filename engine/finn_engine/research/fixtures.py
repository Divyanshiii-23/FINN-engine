def _wrap(pdf: Pdf, s: str, width: float, size: float) -> list[str]:
    out, cur = [], ""
    for w in s.split():
        t = (cur + " " + w).strip()
        if pdf.width(t, size) > width and cur:
            out.append(cur)
            cur = w
        else:
            cur = t
    if cur:
        out.append(cur)
    return out


def _flow(pdf: Pdf, paras: list[tuple[str, float]], first_page: pymupdf.Page | None = None, y0: float = 60) -> None:
    """Writes paragraphs top to bottom, starting new pages as needed. Blank string = spacer."""
    p = first_page or pdf.page()
    y = y0
    for text, size in paras:
        if not text:
            y += 8
            continue
        for line in _wrap(pdf, text, 500, size):
            if y > 790:
                p = pdf.page()
                y = 60
            pdf.text(p, (48, y), line, size)
            y += size * 1.45
        y += 5


