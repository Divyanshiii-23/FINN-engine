def transcript_pdf(c: Co, q: str, path: Path) -> None:
    pdf = Pdf(c.rupee)
    d = CALL_ON[q]
    p = pdf.page()
    pdf.text(p, (48, 50), c.name, 13)
    pdf.text(p, (48, 70), f"{q} Earnings Conference Call", 11)
    pdf.text(p, (48, 86), f"{MONTH[d.month]} {d.day}, {d.year}", 10)
    paras: list[tuple[str, float]] = [("", 0), ("Management:", 10)]
    paras += [(f"{n} - {t}" if n.startswith("Dr.") else f"{'Ms.' if n.split()[0] in FEMALE else 'Mr.'} {n} - {t}", 10) for n, t in c.management]
    paras += [("", 0), ("Note: This transcript has been edited for readability and does not purport to be a verbatim record of the proceedings.", 9), ("", 0)]
    mod = (f"Moderator: Ladies and gentlemen, good day and welcome to the {q} earnings conference call of {c.name}. As a reminder, all participant lines will be in the "
           f"listen-only mode. I now hand the conference over to {c.management[0][0]}. Thank you and over to you.")
    paras.append((mod, 10))
    turns = list(c.transcripts[q])
    # Neutral Q&A that carries no claims, so scripted statements land on later pages as they do in real transcripts.
    first_q = next((i for i, t in enumerate(turns) if t[0] == "Q"), len(turns))
    filler: list[tuple[str, str]] = []
    for i, (qq, aa) in enumerate(FILLER[: 4 + (sum(map(ord, c.symbol + q)) % 4)]):
        filler += [("Q", qq), (c.management[i % len(c.management)][0], aa)]
    turns = turns[:first_q] + filler + turns[first_q:]
    ai = 0
    qa_started = False
    for spk, text in turns:
        if spk == "Q":
            an, firm = c.analysts[ai % len(c.analysts)]
            ai += 1
            cue = "We will now begin the question-and-answer session. The first question is from the line of" if not qa_started else "The next question is from the line of"
            paras.append((f"Moderator: Thank you very much. {cue} {an} from {firm}. Please go ahead.", 10))
            paras.append((f"{an}: {text}", 10))
            qa_started = True
            continue
        if spk == c.management[0][0] and not qa_started and turns.index((spk, text)) == 0:
            text = (f"Thank you. Good evening everyone and thank you for joining us. Some of the statements on this call may be forward-looking statements, and actual results may differ "
                    f"materially from those expressed. " + text)
        paras.append((f"{spk.removeprefix('Dr. ')}: {text}" if spk.startswith("Dr.") else f"{spk}: {text}", 10))
    paras.append(("Moderator: Thank you. On behalf of the company, that concludes this conference. Thank you for joining us and you may now disconnect your lines.", 10))
    _flow(pdf, paras, p, 104)
    pdf.save(path)


def deck_pdf(c: Co, q: str, path: Path) -> None:
    pdf = Pdf(c.rupee)
    slides = c.presentations[q]
    if slides and slides[0][0] == "SCANNED":
        # An image-only deck: a rendered picture, no text layer.
        src = pymupdf.open()
        sp = src.new_page(width=842, height=595)
        sp.insert_text((36, 24), STAMP, fontsize=9, color=(0.75, 0, 0))
        sp.insert_text((60, 120), f"{c.name} - {q} investor presentation", fontsize=22)
        pix = sp.get_pixmap(dpi=60)
        for _ in range(3):
            pg = pdf.doc.new_page(width=842, height=595)
            pg.insert_image(pg.rect, pixmap=pix)
        pdf.save(path)
        return
    p = pdf.page(landscape=True)
    pdf.text(p, (60, 200), c.name, 24)
    pdf.text(p, (60, 240), f"Investor presentation - {q}", 16)
    for title, bullets in slides:
        p = pdf.page(landscape=True)
        pdf.text(p, (60, 70), title, 18)
        for i, b in enumerate(bullets):
            pdf.text(p, (80, 120 + i * 34), b, 13)
    p = pdf.page(landscape=True)
    pdf.text(p, (60, 260), "Thank you", 20)
    pdf.save(path)


