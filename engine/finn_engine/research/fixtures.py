# ------------------------------------------------------------------ PDF writers

class Pdf:
    def __init__(self, rupee: bool):
        self.doc = pymupdf.open()
        self.rupee = rupee and RUPEE_FONT.exists()

    def page(self, landscape: bool = False) -> pymupdf.Page:
        p = self.doc.new_page(width=842 if landscape else 595, height=595 if landscape else 842)
        p.insert_text((36, 24), STAMP, fontsize=7, color=(0.75, 0, 0))
        if self.rupee:
            p.insert_font(fontname="carl", fontfile=str(RUPEE_FONT))
        return p

    def text(self, p: pymupdf.Page, xy: tuple[float, float], s: str, size: float = 8.0) -> None:
        if self.rupee:
            p.insert_text(xy, s, fontsize=size, fontname="carl")
        else:
            p.insert_text(xy, s.replace("₹", "Rs. "), fontsize=size)

    def width(self, s: str, size: float) -> float:
        if self.rupee:
            return pymupdf.Font(fontfile=str(RUPEE_FONT)).text_length(s, fontsize=size)
        return pymupdf.get_text_length(s.replace("₹", "Rs. "), fontsize=size)

    def save(self, path: Path) -> None:
        self.doc.save(path)


def _date(per_end: date) -> str:
    return per_end.strftime("%d.%m.%Y")


def _columns(q: str) -> list[tuple[str, str, str]]:
    """(period label, header date, column caption) in SEBI order for the filing for quarter q."""
    p = P.parse(q)
    assert p
    fy = p[1]
    prev, yago = P.prev_q(q), P.shift_year(q)
    cols = [(q, _date(P.end_of(q)), "Quarter ended"), (prev, _date(P.end_of(prev)), "Quarter ended"), (yago, _date(P.end_of(yago)), "Quarter ended")]
    n = int(p[0][1])
    if n in (2, 3):
        ytd = {2: "H1", 3: "9M"}[n]
        cols += [(f"{ytd} FY{fy % 100:02d}", _date(P.end_of(q)), "Year to date"), (f"{ytd} FY{(fy - 1) % 100:02d}", _date(P.end_of(yago)), "Year to date")]
    if n == 4:
        cols += [(f"FY{fy % 100:02d}", _date(P.end_of(q)), "Year ended"), (f"FY{(fy - 1) % 100:02d}", _date(P.end_of(yago)), "Year ended")]
    else:
        cols += [(f"FY{(fy - 1) % 100:02d}", _date(date(fy - 1, 3, 31)), "Year ended")]
    return cols


def _val(c: Co, period: str, key: str, scale: float) -> float | None:
    qs = P.quarters(period)
    if not all(x in c.pl for x in qs):
        return None
    return r2(sum(c.pl[x].get(key, 0) for x in qs) * scale) if key in c.pl[qs[0]] else None


def _table(pdf: Pdf, p: pymupdf.Page, y: float, header: list[str], dates: list[str], rows: list[tuple[str, str, list[str]]], x0: float = 330, step: float = 82) -> None:
    xs = [x0 + i * step for i in range(len(dates))]
    for x, h in zip(xs, header):
        pdf.text(p, (x - pdf.width(h, 6.5) / 2, y), h, 6.5)
    for x, d in zip(xs, dates):
        pdf.text(p, (x - pdf.width(d, 7) / 2, y + 11), d, 7)
    y += 28
    for serial, label, vals in rows:
        if serial:
            pdf.text(p, (36, y), serial, 7.2)
        pdf.text(p, (58 if not label.startswith("  ") else 70, y), label.strip(), 7.2)
        for x, v in zip(xs, vals):
            pdf.text(p, (x - pdf.width(v, 7.2) / 2, y), v, 7.2)
        y += 13


