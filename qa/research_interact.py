import os
import re
from playwright.sync_api import sync_playwright, expect
B = os.environ.get("FINN_URL", "http://localhost:3000"); OUT = os.environ.get("FINN_QA_OUT", "/tmp/finn-qa")
os.makedirs(OUT, exist_ok=True)
errs, ok = [], []
def check(name, cond):
    ok.append((name, bool(cond))); print(("PASS " if cond else "FAIL ") + name)
with sync_playwright() as p:
    br = p.chromium.launch(); ctx = br.new_context(viewport=dict(width=390, height=844), device_scale_factor=2); pg = ctx.new_page()
    pg.on("console", lambda m: m.type == "error" and errs.append(m.text)); pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto(f"{B}/research"); pg.wait_for_timeout(600)
    box = pg.get_by_role("combobox")
    box.fill("kav"); pg.wait_for_timeout(600)
    check("search finds fixture with report", pg.get_by_role("option").filter(has_text="KAVERI").filter(has_text="Report as of").count() == 1)
    box.fill("zzzq"); pg.wait_for_timeout(600)
    check("unlisted ticker offers 'try anyway'", pg.get_by_text("Try ZZZQ anyway").count() == 1)
    box.fill("polycab"); pg.wait_for_timeout(700)
    check("real NSE ticker from equity list", pg.get_by_role("option").filter(has_text="Polycab India Limited").count() >= 1)
    box.press("Enter"); pg.wait_for_url(re.compile(r"/research/POLYCAB$"))
    pg.wait_for_timeout(800)
    (pg.get_by_role("button", name="Research POLYCAB") if pg.get_by_role("button", name="Research POLYCAB").count() else pg.get_by_role("button", name="Try again")).click()
    pg.wait_for_selector("text=Researching POLYCAB", timeout=5000)
    check("job progress shown", pg.get_by_text("Researching POLYCAB").count() == 1)
    pg.screenshot(path=f"{OUT}/i-titan-running.png")
    pg.wait_for_selector("text=None of the filing sources", timeout=90000)
    check("unreachable sources reported, identity kept", pg.get_by_text("Polycab India Limited").count() >= 1 and pg.get_by_text("Nothing has been filled in").count() == 1)
    pg.screenshot(path=f"{OUT}/i-titan-error.png", full_page=True)
    pg.goto(f"{B}/research/KAVERI"); pg.wait_for_selector("#snapshot")
    pg.locator("#snapshot table button").first.click(); pg.wait_for_timeout(300)
    check("reported figure opens row as printed", pg.get_by_role("dialog").get_by_text("Row as printed").count() == 1)
    pg.keyboard.press("Escape")
    pg.locator("#snapshot table tr").nth(1).locator("button").nth(2).click(); pg.wait_for_timeout(300)
    dlg = pg.get_by_role("dialog")
    check("computed figure shows formula", dlg.get_by_text("Formula").count() == 1)
    dlg.locator("ul button").first.click(); pg.wait_for_timeout(300)
    check("input chain leads to reported row", dlg.get_by_text("Row as printed").count() == 1)
    pg.keyboard.press("Escape")
    row = pg.locator("#nvn li button[aria-expanded]").first
    before = row.get_attribute("aria-expanded"); row.click(); pg.wait_for_timeout(200)
    check("ledger row toggles", row.get_attribute("aria-expanded") != before)
    pg.locator("#trajectory").get_by_role("radio", name="Table").click(); pg.wait_for_timeout(200)
    check("chart/table toggle", pg.locator("#trajectory table").count() >= 2)
    th = pg.locator("#guidance button[aria-expanded]").last; th.click(); pg.wait_for_timeout(200)
    check("commentary theme expands", th.get_attribute("aria-expanded") == "true")
    pg.locator("nav[aria-label=Sections] a", has_text="6 Narrative").click(); pg.wait_for_timeout(300)
    check("section nav jumps", pg.url.endswith("#nvn"))
    pg.get_by_role("button", name="Refresh").click()
    pg.wait_for_selector("text=Refresh", timeout=30000); pg.wait_for_timeout(1500)
    check("refresh re-runs and reloads", pg.get_by_role("button", name="Refresh").count() == 1 and "Refresh failed" not in pg.content())
    pg.goto(f"{B}/research/CORAL"); pg.wait_for_timeout(800)
    check("company without documents explains gaps", pg.get_by_text("No results filing could be read").count() >= 1)
    pg.screenshot(path=f"{OUT}/i-coral.png", full_page=True)
    pg.goto(f"{B}/research/bad%24sym"); pg.wait_for_timeout(800)
    check("invalid symbol message", pg.get_by_text("isn't an NSE symbol").count() == 1)
    br.close()
print("console errors:", errs)
print(sum(c for _, c in ok), "/", len(ok), "passed")
